#if os(macOS)
  import AppKit
  import Foundation
  import Testing

  @testable import BlurtEngine

  /// Issue 310: clipboard history apps saved every dictation, and the restore added the
  /// user's old clipboard again as a new entry. Blurt's own writes now carry the
  /// nspasteboard.org transient marker. These tests use a private, uniquely named
  /// pasteboard, so they never read or change the user's clipboard.
  @Suite("SystemClipboard history markers", .serialized)
  struct SystemClipboardMarkerTests {

    private func withPrivatePasteboard(_ body: (SystemClipboard, NSPasteboard) throws -> Void) rethrows {
      let name = NSPasteboard.Name("app.blurt.tests.\(UUID().uuidString)")
      let pb = NSPasteboard(name: name)
      defer { pb.releaseGlobally() }
      try body(SystemClipboard(pasteboardName: name), pb)
    }

    @Test("the transcript written for a paste is marked transient")
    func transcriptIsTransient() {
      withPrivatePasteboard { clip, pb in
        pb.clearContents()
        pb.setString("original", forType: .string)

        _ = clip.writeAndPrepareRestore("dictated text")

        #expect(pb.string(forType: .string) == "dictated text")
        let types = pb.types ?? []
        #expect(types.contains(SystemClipboard.transientType))
        #expect(types.contains(SystemClipboard.autoGeneratedType))
      }
    }

    @Test("the restore brings the old contents back, marked transient")
    func restoreIsTransient() {
      withPrivatePasteboard { clip, pb in
        pb.clearContents()
        pb.setString("original", forType: .string)

        let restore = clip.writeAndPrepareRestore("dictated text")
        restore()

        #expect(pb.string(forType: .string) == "original")
        #expect((pb.types ?? []).contains(SystemClipboard.transientType))
      }
    }

    @Test("a transcript left for a manual paste stays in history")
    func manualPasteFallbackIsNotTransient() {
      withPrivatePasteboard { clip, pb in
        clip.write("paste me")
        #expect(pb.string(forType: .string) == "paste me")
        #expect(!(pb.types ?? []).contains(SystemClipboard.transientType))
      }
    }

    @Test("Blurt names itself as the source when it has a bundle identifier")
    func sourceMarker() {
      withPrivatePasteboard { clip, pb in
        clip.write("paste me")
        if let bundleID = Bundle.main.bundleIdentifier {
          #expect(pb.string(forType: SystemClipboard.sourceType) == bundleID)
        } else {
          #expect(pb.string(forType: SystemClipboard.sourceType) == nil)
        }
      }
    }
  }
#endif
